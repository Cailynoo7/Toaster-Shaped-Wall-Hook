r=param("dial_radius",10.5)
d=param("dial_depth",4)
gw=param("dial_grip_width",3.5)
ga=param("dial_grip_angle",35)
gh=param("dial_grip_height",16)
s=Rot(90,0,0)*Cylinder(r,d)
s=fillet(s.edges(),1.5)
gt=param("dial_grip_depth",5.44)
grip=Box(gw,gt,gh)
model_scale=param("dial_uniform_scale",0.625)
side_r=param("dial_grip_side_round_mm",0.45)
grip=fillet(grip.edges().filter_by(Axis.Y),side_r/model_scale)
# Side corners rounded; disk-contact perimeter receives no blend.
grip=fillet(grip.faces().sort_by(Axis.Y)[0].edges(),0.6)
grip=Rot(0,ga,0)*grip
s=s+Pos(0,-d/2-gt/2+0.25,0)*grip
s.color=srgb("#edb56c")
s=scale(s,by=model_scale)
axle_d=param("dial_axle_diameter_mm",3)
axle_len=param("dial_axle_length_mm",5.0125)
axle_y=param("dial_axle_center_y_mm",3.55625)
s=s+Pos(0,axle_y,0)*Rot(90,0,0)*Cylinder(axle_d/2,axle_len)
s.color=srgb("#edb56c")
publish("dial",s,"v29 侧边圆角旋钮",material="pla")
