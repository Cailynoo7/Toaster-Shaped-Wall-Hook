w=param("button_3_width",11)
h=param("button_3_height",10)
d=param("button_3_depth",3)
corner_r=param("button_3_outline_round",2.5)
edge_r=param("button_3_face_edge_round",1.25)
s=Box(w,d,h)
s=fillet(s.edges().filter_by(Axis.Y),corner_r)
s=fillet(s.faces().sort_by(Axis.Y)[0].edges(),edge_r)
s.color=srgb("#edb56c")
s=scale(s,by=param("button_3_uniform_scale",0.625))
plug_w=param("button_3_plug_width_mm",4.8)
plug_h=param("button_3_plug_height_mm",5.1125)
plug_r=param("button_3_plug_corner_mm",1.4)
plug_d=param("button_3_plug_depth_mm",1.25)
# The rear shoulder stays square; an integral key seats in the shallow socket.
with BuildSketch(Plane.XZ.offset(-(d*0.625/2-0.05))) as key_sk:
    RectangleRounded(plug_w,plug_h,plug_r)
s=s+extrude(key_sk.sketch,amount=-plug_d-0.05)
s.color=srgb("#edb56c")
publish("button_3",s,"v31 金色按钮",material="pla")
